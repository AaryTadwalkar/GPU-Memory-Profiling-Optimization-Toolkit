# Data Models for Workload Orchestration
# ---------------------------------------------------------------------------

@dataclass
class WorkloadSpec:
    """
    1. The use of class:
       Defines the configuration, requirements, and execution details of a workload.
    2. Fields:
       - workload_id: Unique string identifying this workload instance (e.g. 'cnn_b16_1').
       - workload_name: Model or benchmark name (e.g. 'cnn', 'resnet', 'transformer').
       - estimated_bytes: Declared or estimated GPU memory requirement in bytes.
       - batch_size: Model batch size if applicable.
       - precision: Precision setting ('fp32', 'fp16', 'bf16') if applicable.
       - command: Optional CLI argument list to run as a subprocess in live mode.
       - metadata: Optional arbitrary dictionary for custom runner parameters.
    """
    workload_id: str
    workload_name: str
    estimated_bytes: int
    batch_size: Optional[int] = None
    precision: Optional[str] = None
    command: Optional[List[str]] = None
    metadata: Optional[Dict[str, Any]] = None


@dataclass
class WorkloadExecutionResult:
    """
    1. The use of class:
       Standard result returned by an injected or live workload runner.
    2. Fields:
       - status: 'SUCCESS', 'FAILED', or 'OOM'.
       - runtime_s: Elapsed wall-clock time in seconds.
       - peak_memory_bytes: Observed peak GPU memory used by the process in bytes.
       - oom_occurred: True if an out-of-memory error occurred.
       - error_message: Error string or traceback if execution failed.
       - output_csv_path: Telemetry CSV path generated by profiler, if any.
       - notes: Additional diagnostic information.
    """
    status: str = ExperimentStatus.SUCCESS
    runtime_s: Optional[float] = None
    peak_memory_bytes: Optional[int] = None
    oom_occurred: bool = False
    error_message: Optional[str] = None
    output_csv_path: Optional[str] = None
    notes: Optional[str] = None


# Type alias for a workload execution callable
WorkloadRunner = Callable[[WorkloadSpec], WorkloadExecutionResult]


# ---------------------------------------------------------------------------
# Default Mock Runner (for safe CPU-only testing)
# ---------------------------------------------------------------------------

def default_mock_runner(spec: WorkloadSpec) -> WorkloadExecutionResult:
    """
    Safe CPU-only default runner used when no custom runner is provided.
    Simulates a successful execution without invoking hardware.
    """
    return WorkloadExecutionResult(
        status=ExperimentStatus.SUCCESS,
        runtime_s=0.01,
        peak_memory_bytes=None,
        oom_occurred=False,
        notes="Executed via default mock runner (uninstrumented peak)",
    )


def real_gpu_workload_runner(spec: WorkloadSpec) -> WorkloadExecutionResult:
    """
    1. The use of function:
       Executes an authentic PyTorch deep learning workload on physical CUDA GPU hardware,
       measuring actual execution runtime and peak GPU memory allocated with strict error handling,
       headroom pre-checking, and guaranteed resource reclamation.

    2. How does the specific function work:
       Validates PyTorch and CUDA availability. Evaluates device free memory against the declared
       estimated requirement plus safety buffer. If insufficient, returns OOM status to protect
       system stability. Constructs a real neural network module (Small CNN, ResNet Stage, or Linear MLP)
       sized according to spec, sets precision (FP32 or FP16), creates input tensors, resets CUDA peak
       memory stats, and executes the specified pass (forward-only or forward-backward). Records elapsed
       wall-clock time and peak allocated VRAM (via torch.cuda.max_memory_allocated()). In a guaranteed
       finally block, explicitly deletes all models and tensors, invokes gc.collect(), and empties the CUDA cache.

    3. Concepts used in the function:
       Hardware-level deep learning execution, PyTorch peak memory profiling, CUDA synchronization,
       dynamic precision casting, safe headroom validation, and deterministic resource release.

    4. Places where this function is imported and used:
       Imported by dashboard/app.py in Tab 5 (Workload Manager) and Tab 7 (Profiling & Benchmark Reports),
       and tested in tests/test_real_benchmarks.py.

    5. Final output of the function, before and after:
       Before: WorkloadSpec configuration parameters.
       After: WorkloadExecutionResult populated with actual runtime_s, peak_memory_bytes, status,
              and detailed execution diagnostics.
    """
    if not HAS_TORCH or not torch.cuda.is_available():
        return WorkloadExecutionResult(
            status=ExperimentStatus.FAILED,
            runtime_s=None,
            peak_memory_bytes=None,
            oom_occurred=False,
            error_message="CUDA accelerator not available for hardware execution",
            notes="Hardware execution requested but CUDA is unavailable",
        )

    # Pre-execution safety headroom check
    try:
        free_bytes, _ = torch.cuda.mem_get_info()
    except Exception as exc:
        return WorkloadExecutionResult(
            status=ExperimentStatus.FAILED,
            runtime_s=None,
            peak_memory_bytes=None,
            oom_occurred=False,
            error_message=f"Failed to query device memory: {exc}",
        )

    safe_margin = 256 * 1024 * 1024  # 256 MB buffer
    if free_bytes < (spec.estimated_bytes + safe_margin):
        return WorkloadExecutionResult(
            status=ExperimentStatus.OOM,
            runtime_s=None,
            peak_memory_bytes=None,
            oom_occurred=True,
            error_message=(
                f"Insufficient safe VRAM headroom ({free_bytes // (1024*1024)} MB available < "
                f"estimated {spec.estimated_bytes // (1024*1024)} MB + 256 MB safety buffer)"
            ),
            notes="Aborted pre-execution to prevent unmanaged CUDA Out-Of-Memory condition",
        )

    model = None
    inputs = None
    outputs = None
    loss = None
    start_time = time.time()

    try:
        # Pre-cleanup and peak reset
        gc.collect()
        torch.cuda.empty_cache()
        torch.cuda.reset_peak_memory_stats()

        batch_size = max(1, spec.batch_size or 16)
        name_lower = spec.workload_name.lower()

        # Build realistic PyTorch architecture based on workload specification
        if "resnet" in name_lower:
            model = torch.nn.Sequential(
                torch.nn.Conv2d(64, 128, kernel_size=3, padding=1),
                torch.nn.BatchNorm2d(128),
                torch.nn.ReLU(),
                torch.nn.Conv2d(128, 128, kernel_size=3, padding=1),
                torch.nn.BatchNorm2d(128),
                torch.nn.ReLU(),
            ).cuda()
            inputs = torch.randn(batch_size, 64, 32, 32, device="cuda")
        elif "mlp" in name_lower or "linear" in name_lower:
            model = torch.nn.Sequential(
                torch.nn.Linear(1024, 2048),
                torch.nn.ReLU(),
                torch.nn.Linear(2048, 1024),
            ).cuda()
            inputs = torch.randn(batch_size, 1024, device="cuda")
        else:
            # Default: Small CNN
            model = torch.nn.Sequential(
                torch.nn.Conv2d(3, 32, kernel_size=3, padding=1),
                torch.nn.BatchNorm2d(32),
                torch.nn.ReLU(),
                torch.nn.Conv2d(32, 64, kernel_size=3, padding=1),
                torch.nn.BatchNorm2d(64),
                torch.nn.ReLU(),
                torch.nn.AdaptiveAvgPool2d((1, 1)),
            ).cuda()
            inputs = torch.randn(batch_size, 3, 64, 64, device="cuda")

        # Precision handling
        is_half = spec.precision and ("16" in spec.precision.lower())
        if is_half:
            model = model.half()
            inputs = inputs.half()

        pass_type = "forward_only"
        if spec.metadata and spec.metadata.get("pass_type") == "forward_backward":
            pass_type = "forward_backward"

        if pass_type == "forward_backward":
            outputs = model(inputs)
            loss = outputs.sum()
            loss.backward()
            pass_desc = "Forward + Backward Pass"
        else:
            with torch.no_grad():
                outputs = model(inputs)
            pass_desc = "Forward-Only Pass"

        torch.cuda.synchronize()
        runtime_s = round(time.time() - start_time, 4)
        peak_bytes = int(torch.cuda.max_memory_allocated())
        gpu_name = torch.cuda.get_device_name(0)

        return WorkloadExecutionResult(
            status=ExperimentStatus.SUCCESS,
            runtime_s=runtime_s,
            peak_memory_bytes=peak_bytes,
            oom_occurred=False,
            notes=f"Executed real GPU {pass_desc} (Batch {batch_size}, {spec.precision or 'FP32'}) on {gpu_name}",
        )

    except Exception as exc:
        runtime_s = round(time.time() - start_time, 4)
        err_str = str(exc)
        is_oom = "out of memory" in err_str.lower() or "cuda oom" in err_str.lower()
        return WorkloadExecutionResult(
            status=ExperimentStatus.OOM if is_oom else ExperimentStatus.FAILED,
            runtime_s=runtime_s,
            peak_memory_bytes=None,
            oom_occurred=is_oom,
            error_message=err_str,
            notes=f"Exception encountered during hardware execution: {type(exc).__name__}",
        )

    finally:
        del model, inputs, outputs, loss
        gc.collect()
        if HAS_TORCH and torch.cuda.is_available():
            torch.cuda.empty_cache()


# ---------------------------------------------------------------------------
# Helper: Construct ExperimentResult
# ---------------------------------------------------------------------------

def _build_result_record(
    experiment_id: str,
    spec: WorkloadSpec,
    exec_res: WorkloadExecutionResult,
    num_concurrent: int,
    admission_decision: Optional[str],
    hardware_meta: Dict[str, Any],
    timestamp: float,
) -> ExperimentResult:
    """Combines metadata, spec, and execution outcome into an ExperimentResult."""
    return ExperimentResult(
        experiment_id=experiment_id,
        run_id=f"{spec.workload_id}_{uuid.uuid4().hex[:8]}",
        timestamp=timestamp,
        workload_name=spec.workload_name,
        gpu_model=hardware_meta.get("gpu_model"),
        vram_capacity_bytes=hardware_meta.get("vram_capacity_bytes"),
        driver_version=hardware_meta.get("driver_version"),
        cuda_version=hardware_meta.get("cuda_version"),
        pytorch_version=hardware_meta.get("pytorch_version"),
        batch_size=spec.batch_size,
        precision=spec.precision,
        num_concurrent=num_concurrent,
        admission_decision=admission_decision,
        status=exec_res.status,
        runtime_s=exec_res.runtime_s,
        peak_memory_bytes=exec_res.peak_memory_bytes,
        estimated_requirement_bytes=spec.estimated_bytes,
        oom_occurred=exec_res.oom_occurred,
        error_message=exec_res.error_message,
        output_csv_path=exec_res.output_csv_path,
        notes=exec_res.notes,
    )


# ---------------------------------------------------------------------------
# Baseline Experiment Orchestrator
# ---------------------------------------------------------------------------

def run_baseline_experiment(
    workloads: Sequence[WorkloadSpec],
    experiment_id: str = "baseline_concurrent",
    runner_fn: Optional[WorkloadRunner] = None,
    max_concurrency: Optional[int] = None,
    hardware_metadata: Optional[Dict[str, Any]] = None,
    writer: Optional[ExperimentResultWriter] = None,
) -> List[ExperimentResult]:
    """
    1. The use of function:
       Orchestrates baseline concurrent workload execution WITHOUT admission control.
    2. How it works:
       - Launches all workloads concurrently (or with specified concurrency pool).
       - Does NOT request headroom or make reservations with the AdmissionController.
       - For each workload, `admission_decision` is None.
       - Captures execution outcomes, runtime, observed peaks, and errors.
       - Records results immediately via writer if provided.
    3. Error handling:
       - If a runner raises an exception, the error is preserved in `error_message`
         with `status="FAILED"`. OOM exceptions are flagged with `oom_occurred=True`.
    4. Concepts:
       Baseline comparison, multi-process scheduling, exception resilience.
    5. Output:
       List of ExperimentResult objects.
    """
    runner = runner_fn or default_mock_runner
    hardware_meta = hardware_metadata or detect_environment_metadata(safe_cpu_only=True)
    num_concurrent = len(workloads)
    pool_size = max_concurrency or max(1, num_concurrent)

    results: List[ExperimentResult] = []

    def _execute_workload(spec: WorkloadSpec) -> ExperimentResult:
        start_time = time.time()
        try:
            exec_res = runner(spec)
        except Exception as exc:
            err_str = str(exc)
            is_oom = "out of memory" in err_str.lower() or "cuda oom" in err_str.lower()
            exec_res = WorkloadExecutionResult(
                status=ExperimentStatus.OOM if is_oom else ExperimentStatus.FAILED,
                runtime_s=time.time() - start_time,
                peak_memory_bytes=None,
                oom_occurred=is_oom,
                error_message=err_str,
                notes=f"Exception raised during execution: {type(exc).__name__}",
            )

        res_record = _build_result_record(
            experiment_id=experiment_id,
            spec=spec,
            exec_res=exec_res,
            num_concurrent=num_concurrent,
            admission_decision=None,  # No admission control in baseline
            hardware_meta=hardware_meta,
            timestamp=start_time,
        )
        if writer:
            writer.write_result(res_record)
        return res_record

    if pool_size > 1 and len(workloads) > 1:
        with concurrent.futures.ThreadPoolExecutor(max_workers=pool_size) as executor:
            future_to_spec = [executor.submit(_execute_workload, spec) for spec in workloads]
            for future in future_to_spec:
                results.append(future.result())
    else:
        for spec in workloads:
            results.append(_execute_workload(spec))

    return results


# ---------------------------------------------------------------------------
# Controlled Experiment Orchestrator
# ---------------------------------------------------------------------------

def run_controlled_experiment(
    workloads: Sequence[WorkloadSpec],
    controller: AdmissionController,
    experiment_id: str = "controlled_admission",
    runner_fn: Optional[WorkloadRunner] = None,
    max_concurrency: Optional[int] = None,
    hardware_metadata: Optional[Dict[str, Any]] = None,
    writer: Optional[ExperimentResultWriter] = None,
    retry_deferred: bool = False,
    poll_interval_s: float = 0.02,
    max_retry_duration_s: float = 1.0,
) -> List[ExperimentResult]:
    """
    1. The use of function:
       Orchestrates multi-process workload execution WITH cooperative admission control.
    2. How it works:
       - For each workload, queries `controller.request(spec.workload_id, spec.estimated_bytes)`.
       - If ADMIT:
         - Launches the workload via `runner_fn(spec)`.
         - When finished, records observed peak in controller and calls `controller.release()`.
         - Builds ExperimentResult with status=SUCCESS/FAILED and admission_decision="ADMIT".
       - If DEFER:
         - If `retry_deferred=True`, polls periodically until admitted or timeout.
         - If still deferred, marks status="DEFERRED", admission_decision="DEFER".
         - Workload is NOT executed.
       - If REJECT:
         - Immediately marks status="REJECTED", admission_decision="REJECT".
         - Workload is NOT executed.
    3. Safety & Cleanup:
       - Guaranteed reservation release: even if runner_fn crashes, raises an OOM,
         or fails, `controller.release(spec.workload_id)` is invoked in a finally block.
       - Preserves distinct status codes: DEFERRED and REJECTED are distinct from FAILED.
       - Never conflates estimated memory with observed peak memory.
    4. Concepts:
       Cooperative resource admission, reservation lifecycle, audit logging.
    5. Output:
       List of ExperimentResult objects.
    """
    runner = runner_fn or default_mock_runner
    hardware_meta = hardware_metadata or detect_environment_metadata(safe_cpu_only=True)
    num_concurrent = len(workloads)
    pool_size = max_concurrency or max(1, num_concurrent)

    results: List[ExperimentResult] = []

    def _process_workload(spec: WorkloadSpec) -> ExperimentResult:
        start_time = time.time()

        # Step 1: Request admission from the controller
        decision, event = controller.request(
            workload_id=spec.workload_id,
            estimated_bytes=spec.estimated_bytes,
        )

        # Step 2: Handle DEFER with optional retries
        # Intermediate polls pass log_decision=False to avoid flooding decision_log.
        # If admitted on retry, the final ADMIT event is logged explicitly.
        if decision == AdmissionDecision.DEFER and retry_deferred:
            deadline = time.time() + max_retry_duration_s
            while time.time() < deadline:
                time.sleep(poll_interval_s)
                poll_decision, poll_event = controller.request(
                    workload_id=spec.workload_id,
                    estimated_bytes=spec.estimated_bytes,
                    log_decision=False,
                )
                if poll_decision == AdmissionDecision.ADMIT:
                    decision = poll_decision
                    event = poll_event
                    controller.log_decision_event(event)
                    break

        # Step 3: Handle outcomes
        if decision == AdmissionDecision.REJECT:
            metadata_dict = {}
            if "metadata_json" in event:
                try:
                    import json
                    metadata_dict = json.loads(event["metadata_json"])
                except Exception:
                    pass
            reject_msg = metadata_dict.get("reject_reason", "Workload rejected by admission policy")

            exec_res = WorkloadExecutionResult(
                status=ExperimentStatus.REJECTED,
                runtime_s=None,
                peak_memory_bytes=None,
                oom_occurred=False,
                error_message=reject_msg,
                notes="Workload rejected: violates configured controller budget or policy cap",
            )

        elif decision == AdmissionDecision.DEFER:
            exec_res = WorkloadExecutionResult(
                status=ExperimentStatus.DEFERRED,
                runtime_s=None,
                peak_memory_bytes=None,
                oom_occurred=False,
                error_message="Insufficient safe headroom at scheduling time",
                notes="Workload deferred: waiting for concurrent reservations to release",
            )

        elif decision == AdmissionDecision.ADMIT:
            # ADMITTED: Execute workload and ensure reservation is released in finally block
            try:
                exec_res = runner(spec)
                if exec_res.peak_memory_bytes is not None:
                    controller.record_observed_peak(spec.workload_id, exec_res.peak_memory_bytes)
            except Exception as exc:
                err_str = str(exc)
                is_oom = "out of memory" in err_str.lower() or "cuda oom" in err_str.lower()
                exec_res = WorkloadExecutionResult(
                    status=ExperimentStatus.OOM if is_oom else ExperimentStatus.FAILED,
                    runtime_s=time.time() - start_time,
                    peak_memory_bytes=None,
                    oom_occurred=is_oom,
                    error_message=err_str,
                    notes=f"Exception raised during execution: {type(exc).__name__}",
                )
            finally:
                controller.release(spec.workload_id)

        else:
            exec_res = WorkloadExecutionResult(
                status=ExperimentStatus.FAILED,
                runtime_s=None,
                peak_memory_bytes=None,
                oom_occurred=False,
                error_message=f"Unknown admission decision: {decision}",
            )

        res_record = _build_result_record(
            experiment_id=experiment_id,
            spec=spec,
            exec_res=exec_res,
            num_concurrent=num_concurrent,
            admission_decision=decision,
            hardware_meta=hardware_meta,
            timestamp=start_time,
        )
        if writer:
            writer.write_result(res_record)
        return res_record

    if pool_size > 1 and len(workloads) > 1:
        with concurrent.futures.ThreadPoolExecutor(max_workers=pool_size) as executor:
            future_to_spec = [executor.submit(_process_workload, spec) for spec in workloads]
            for future in future_to_spec:
                results.append(future.result())
    else:
        for spec in workloads:
            results.append(_process_workload(spec))

    return results
