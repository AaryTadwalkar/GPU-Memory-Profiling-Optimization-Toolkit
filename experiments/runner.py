"""
File: experiments/runner.py

1. What this file does:
   Implements experiment orchestration for multi-process GPU benchmarking:
   - Baseline concurrent execution (running workloads concurrently without admission control).
   - Cooperative execution (scheduling workloads through the AdmissionController).
   All orchestration is fully testable using injected or mock workload runners without
   accessing GPU, CUDA, or NVML hardware.

2. Overall design:
   Defines `WorkloadSpec` (the workload configuration to run) and `WorkloadExecutionResult`
   (the output from executing a workload). Runners execute workloads either sequentially
   or concurrently using a thread pool.

   COOPERATIVE ADMISSION CONTROL DISCLAIMER:
   The controlled runner coordinates workloads through the AdmissionController on a
   voluntary, cooperative basis. Admission control does NOT provide hardware memory
   isolation or guarantee that external processes, OS graphics, or CUDA driver
   allocations will not cause an unexpected Out-Of-Memory condition.

   Key design constraints:
   - DISTINCT STATUS CODES:
     Workloads deferred or rejected by admission policy receive status DEFERRED
     or REJECTED, distinct from FAILED executions.
   - PRESERVATION OF ERRORS:
     Exceptions and errors during execution are captured and preserved in the
     resulting ExperimentResult rather than swallowed.
   - RESERVATION INTEGRITY:
     In controlled execution, every admitted workload is guaranteed to call
     `controller.release()` upon completion, error, or cancellation to prevent
     reservation leaks.
   - SEPARATION OF ESTIMATED VS OBSERVED:
     `spec.estimated_bytes` is mapped to `estimated_requirement_bytes`, while the
     runner's measured peak is mapped to `peak_memory_bytes`.
   - NO FABRICATED DATA:
     Unmeasured or missing fields remain None.

3. Elements in the file:
   - `WorkloadSpec`: Workload configuration and resource declarations.
   - `WorkloadExecutionResult`: Standard outcome returned by a workload runner.
   - `run_baseline_experiment`: Uncontrolled concurrent execution.
   - `run_controlled_experiment`: Cooperative admission-controlled execution.

4. Final output:
   List of `ExperimentResult` instances, optionally persisted to disk via `ExperimentResultWriter`.
"""

